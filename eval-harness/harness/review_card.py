"""Reviewer view for agent-assist: what a support agent sees next to each draft.

Agent-assist is only a safe default if reviewers catch what the assistant gets wrong. The worst
drafts in the sample (TCK-1006, TCK-1009) are fluent and confident, which is exactly what a busy
reviewer approves on autopilot. Each card therefore leads with the system's decision and the
judge's claim-level flags, each paired with the guide text, so the reviewer checks specific
claims instead of rereading a plausible answer. Cards are ordered riskiest first.

The cards show only what a production reviewer would have: the ticket, the draft, the rules, and
the judge. They never show the reference labels.
"""

from .data import SEVERITIES

SEVERITY_RANK = {s: i for i, s in enumerate(SEVERITIES)}


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "/")


def render_card(ticket, judge_eval: dict, rules_fired: dict[str, str], action, bounce: str | None) -> str:
    decision = {"auto_send": "WOULD AUTO-SEND", "handoff": "HAND OFF", "hold_for_agent": "HOLD FOR AGENT"}[action.action]
    if action.queue:
        decision += f" to {action.queue}"
    lines = [
        f"### {ticket.id}: {decision} (judge: {judge_eval['severity']})",
        "",
        f"**Ticket:** {_cell(ticket.ticket_text)}",
        "",
        "**Draft:**",
        "",
        *[f"> {line}" if line else ">" for line in ticket.assistant_answer.splitlines()],
        "",
    ]
    flagged = [c for c in judge_eval["claims"] if c["verdict"] != "supported"]
    flagged.sort(key=lambda c: c["verdict"] != "contradicted")
    checks = []
    if flagged:
        checks.append("| Verdict | Claim in the draft | What the guide says |")
        checks.append("|---|---|---|")
        for c in flagged:
            evidence = f'"{_cell(c["guide_evidence"])}"' if c["guide_evidence"] else "Not in the guide."
            checks.append(f"| **{c['verdict'].upper()}** ({c['claim_type']}) | {_cell(c['claim'])} | {evidence} |")
        checks.append("")
    for q in judge_eval["sub_questions"]:
        if not q["addressed"]:
            checks.append(f"- **Not answered:** {_cell(q['question'])}")
    esc = judge_eval["escalation"]
    if esc["should_route_to_human"] or esc["assessment"] in {"missing_escalation", "unnecessary_deferral"}:
        checks.append(f"- **Escalation:** {esc['assessment'].replace('_', ' ')}"
                      + ("; the judge says a person or specialist should handle this." if esc["should_route_to_human"] else "."))
    for issue in judge_eval["customer_safety_issues"]:
        checks.append(f"- **Customer safety:** {_cell(issue)}")
    if bounce:
        checks.append(f"- **Bounce:** the draft sends the customer elsewhere ({bounce}); hand the ticket off internally instead.")
    for rule, evidence in rules_fired.items():
        checks.append(f"- **Rule `{rule}`:** {_cell(evidence)}")
    supported = len(judge_eval["claims"]) - len(flagged)
    lines += ["**Check before approving:**", ""] + (checks or ["- Nothing flagged."]) + [
        "", f"_{supported} other claim{'s' if supported != 1 else ''} matched the guide._", ""]
    return "\n".join(lines)


def render_cards(tickets, judge_records: dict, judge_name: str, hits: dict, actions: dict, bounces: dict,
                 audit_rate: float) -> str:
    order = {"handoff": 0, "hold_for_agent": 1, "auto_send": 2}

    def key(t):
        j = judge_records[t.id]["evaluation"]
        flagged = sum(c["verdict"] != "supported" for c in j["claims"])
        return (order[actions[t.id].action], -SEVERITY_RANK[j["severity"]], -flagged, t.id)

    ranked = sorted(tickets, key=key)
    counts = {a: sum(actions[t.id].action == a for t in tickets) for a in order}
    flagged_auto = [t.id for t in tickets if actions[t.id].action == "auto_send"
                    and any(c["verdict"] != "supported" for c in judge_records[t.id]["evaluation"]["claims"])]
    header = [
        "# Reviewer view (agent-assist)",
        "",
        "Generated by `python run_eval.py score`. This is what a support agent would see beside each draft during agent-assist: "
        f"the system's decision, then every claim the LLM judge ({judge_name}) could not match to the guide, with the guide text "
        "next to it. Reference labels are not shown, because a production reviewer would not have them.",
        "",
        "Why: the riskiest drafts in this sample are fluent and confident (TCK-1006 and TCK-1009 promise SSO on the Team plan). "
        "A reviewer skimming a plausible answer will approve it. Pointing at specific claims makes the review a checklist.",
        "",
        f"Decisions under the proposed configuration: {counts['handoff']} hand off, {counts['hold_for_agent']} held for an agent, "
        f"{counts['auto_send']} would auto-send. Of the would-auto-send drafts, {len(flagged_auto)} still carry at least one "
        f"unsupported claim the judge rated harmless ({', '.join(flagged_auto) or 'none'}).",
        "",
        "## Audit policy",
        "",
        "A second reviewer re-checks (`harness/shadow.py: audit_sample`):",
        "",
        "1. every draft approved unchanged although the system would not have auto-sent it;",
        "2. every large edit that the reviewer tagged as none or minor, or left untagged;",
        "3. every record without an edit tag;",
        f"4. a random {audit_rate:.0%} of approved drafts the guardrail would have auto-sent (set in `gates.json`).",
        "",
        "The auditor's severity overrides the reviewer's tag in the shadow-mode gate numbers.",
        "",
        "## Cards (riskiest first)",
        "",
    ]
    cards = [render_card(t, judge_records[t.id]["evaluation"], hits[t.id], actions[t.id], bounces[t.id]) for t in ranked]
    return "\n".join(header) + "\n" + "\n---\n\n".join(cards)
